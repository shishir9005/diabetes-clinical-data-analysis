"""Day 1, step 6: generate, check and freeze the grouped train/test split and 15 CV folds.

Split generation may read the full cleaned file (labels are needed for stratification).
After this script, test rows are used only for split-count/integrity reports and,
on an approved later day, the predeclared final evaluation.

Design (docs/PROJECT_PLAN.md §3.7):
  * test split: StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=42) on all
    rows, groups = profile_id, y = label; fold 0 is the predeclared test set.
  * CV: 3 repeats x 5-fold StratifiedGroupKFold on the training partition,
    random_state = 0, 1, 2  ->  15 folds.
  * Acceptance checks on every fold in the all-rows and deduplicated views.
    If any check fails, nothing is frozen and the script exits non-zero.

History: the 6 Nov 2026 freeze used CV seeds 100, 101, 102 (archived version of this file:
archive/day1_pre_correction_2026-11-07/src/s03_freeze_split.py). On 7 Nov 2026 the owner fixed the
seeds at 0, 1, 2, and the CV folds were regenerated by src/s03b_regenerate_cv_folds.py, which applies
the same fold logic to the frozen training partition without regenerating the train/test split.
Only the CV seed constant changed in this file; the test-split logic is untouched. The script still
refuses to run while frozen outputs exist.

Run with:  <env python> -I -B src/s03_freeze_split.py
Writes (only if every check passes):
  data/splits/split_assignment.csv, data/splits/cv_folds.csv, data/splits/split_config.json
  data/processed/train_rows.csv
  reports/03_split_and_cv.md, reports/03_split_and_cv.json   (report is written either way)
"""
from __future__ import annotations

import json
import os
import stat
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import sklearn  # noqa: E402
from sklearn.model_selection import StratifiedGroupKFold  # noqa: E402

from prep import (ALL_COLUMNS, CLEANED_ALL, RAW_CSV, REPORTS_DIR, SPLITS_DIR, TRAIN_ROWS,  # noqa: E402
                  md_table, sha256_file)

TEST_SEED, TEST_N_SPLITS, TEST_FOLD = 42, 5, 0
CV_SEEDS, CV_N_SPLITS = [0, 1, 2], 5
OUT_ASSIGN = SPLITS_DIR / "split_assignment.csv"
OUT_FOLDS = SPLITS_DIR / "cv_folds.csv"
OUT_CONFIG = SPLITS_DIR / "split_config.json"
FROZEN_OUTPUTS = [OUT_ASSIGN, OUT_FOLDS, OUT_CONFIG, TRAIN_ROWS]

existing = [str(p) for p in FROZEN_OUTPUTS if p.exists()]
if existing:
    sys.exit(f"Refusing to run: frozen outputs already exist {existing}. The split is generated once.")

df = pd.read_csv(CLEANED_ALL)
checks: list[dict] = []


def add_check(scope: str, name: str, ok: bool, detail="") -> None:
    checks.append({"scope": scope, "check": name, "result": "PASS" if ok else "FAIL", "detail": str(detail)})


def counts(frame: pd.DataFrame) -> dict:
    n, pos = len(frame), int(frame["label"].sum())
    return {"rows": n, "groups": int(frame["profile_id"].nunique()), "positive": pos,
            "negative": n - pos, "pct_positive": round(100 * pos / n, 2) if n else float("nan")}


VIEWS = {"all_rows": lambda d: d, "deduplicated": lambda d: d[d["is_first_copy"] == 1]}

# Identifier sanity: with zero conflicting profiles, profile_id must equal record_id.
add_check("identifiers", "profile_id equals record_id for every row (no conflicting profiles)",
          bool((df["profile_id"] == df["record_id"]).all()))

# --- Test split ----------------------------------------------------------------
outer = list(StratifiedGroupKFold(n_splits=TEST_N_SPLITS, shuffle=True, random_state=TEST_SEED)
             .split(np.zeros(len(df)), df["label"], df["profile_id"]))
test_idx = outer[TEST_FOLD][1]
df["partition"] = "train"
df.loc[df.index[test_idx], "partition"] = "test"
train = df[df["partition"] == "train"].reset_index(drop=True)
test = df[df["partition"] == "test"].reset_index(drop=True)

test_rows_report = []
for view, f in VIEWS.items():
    tr, te = f(train), f(test)
    test_rows_report.append({"view": view, "partition": "train", **counts(tr)})
    test_rows_report.append({"view": view, "partition": "test", **counts(te)})
    add_check(f"test split [{view}]", "both classes in training partition", tr["label"].nunique() == 2)
    add_check(f"test split [{view}]", "both classes in test partition", te["label"].nunique() == 2)
    overlap = set(tr["profile_id"]) & set(te["profile_id"])
    add_check(f"test split [{view}]", "no profile group in both partitions", not overlap, f"overlap={len(overlap)}")
add_check("test split", "train + test rows = all rows, disjoint",
          len(train) + len(test) == len(df) and not (set(train.row_id) & set(test.row_id)))

# --- 15 CV folds on the training partition -------------------------------------
fold_rows = []
partitions_by_repeat = []
for r, seed in enumerate(CV_SEEDS):
    col = f"cv_r{r}_fold"
    assign = np.full(len(train), -1)
    times_validated = np.zeros(len(train), dtype=int)
    splits = list(StratifiedGroupKFold(n_splits=CV_N_SPLITS, shuffle=True, random_state=seed)
                  .split(np.zeros(len(train)), train["label"], train["profile_id"]))
    for k, (_, va) in enumerate(splits):
        assign[va] = k
        times_validated[va] += 1
    train[col] = assign
    add_check(f"repeat {r} (seed {seed})", "every training row in exactly one validation fold",
              bool((times_validated == 1).all()), f"min={times_validated.min()}, max={times_validated.max()}")
    partitions_by_repeat.append(frozenset(frozenset(train.loc[train[col] == k, "row_id"]) for k in range(CV_N_SPLITS)))
    for k in range(CV_N_SPLITS):
        for view, f in VIEWS.items():
            v = f(train)
            tr_part, va_part = v[v[col] != k], v[v[col] == k]
            both_tr = tr_part["label"].nunique() == 2
            both_va = va_part["label"].nunique() == 2
            overlap = set(tr_part["profile_id"]) & set(va_part["profile_id"])
            ok = both_tr and both_va and not overlap
            ctr, cva = counts(tr_part), counts(va_part)
            fold_rows.append({
                "repeat": r, "seed": seed, "fold": k, "view": view,
                **{f"train_{a}": b for a, b in ctr.items()}, **{f"val_{a}": b for a, b in cva.items()},
                "both_classes_train": both_tr, "both_classes_val": both_va,
                "profile_overlap": len(overlap), "result": "PASS" if ok else "FAIL",
            })

fold_df = pd.DataFrame(fold_rows)
n_fold_checks = len(fold_df)
n_fold_fail = int((fold_df["result"] == "FAIL").sum())
add_check("CV folds", f"all {n_fold_checks // 2} folds x 2 views pass all three checks", n_fold_fail == 0,
          f"{n_fold_checks - n_fold_fail}/{n_fold_checks} fold-view combinations passed")
add_check("CV folds", "CV folds contain only training rows (no test row in any fold)",
          set(train["row_id"]).isdisjoint(set(test["row_id"])) and len(train) == int((df["partition"] == "train").sum()))
distinct = len(set(partitions_by_repeat))
add_check("CV folds", "the three repeats produce different fold partitions (informational)",
          distinct == len(CV_SEEDS), f"{distinct} distinct partitions out of {len(CV_SEEDS)}")

all_pass = all(c["result"] == "PASS" for c in checks)

# --- Freeze (only if everything passed) ------------------------------------------
created = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
config = {
    "created_utc": created,
    "input_file": "data/processed/cleaned_all_rows.csv",
    "input_sha256": sha256_file(CLEANED_ALL),
    "raw_csv_sha256": sha256_file(RAW_CSV),
    "group_column": "profile_id (16 features identical)",
    "test_split": {"method": "StratifiedGroupKFold", "n_splits": TEST_N_SPLITS, "shuffle": True,
                   "random_state": TEST_SEED, "test_fold_index": TEST_FOLD, "fitted_on": "all 520 rows"},
    "cv": {"method": "StratifiedGroupKFold, repeated", "n_splits": CV_N_SPLITS, "shuffle": True,
           "random_state_per_repeat": CV_SEEDS, "total_folds": CV_N_SPLITS * len(CV_SEEDS),
           "fitted_on": "training partition, all rows",
           "deduplicated_view": "same fold per profile_id; keep rows with is_first_copy == 1"},
    "versions": {"python": sys.version.split()[0], "numpy": np.__version__, "pandas": pd.__version__,
                 "scikit-learn": sklearn.__version__},
    "acceptance_checks_passed": all_pass,
}

if all_pass:
    SPLITS_DIR.mkdir(parents=True, exist_ok=True)
    df[["row_id", "record_id", "profile_id", "is_first_copy", "partition"]].to_csv(OUT_ASSIGN, index=False)
    train[["row_id", "profile_id", "is_first_copy"] + [f"cv_r{r}_fold" for r in range(len(CV_SEEDS))]].to_csv(OUT_FOLDS, index=False)
    OUT_CONFIG.write_text(json.dumps(config, indent=2))
    train[["row_id", "record_id", "profile_id", "is_first_copy"] + ALL_COLUMNS].to_csv(TRAIN_ROWS, index=False)
    for p in FROZEN_OUTPUTS:  # integrity safeguard against accidental edits; not immutability
        os.chmod(p, stat.S_IRUSR | stat.S_IRGRP | stat.S_IROTH)
    config["frozen_file_sha256"] = {str(p.relative_to(SPLITS_DIR.parent.parent)): sha256_file(p) for p in FROZEN_OUTPUTS}

# --- Report ------------------------------------------------------------------------
(REPORTS_DIR / "03_split_and_cv.json").write_text(json.dumps(
    {"config": config, "checks": checks, "test_split_counts": test_rows_report, "cv_folds": fold_rows}, indent=2, default=str))

show_cols = ["repeat", "seed", "fold", "train_rows", "train_groups", "train_positive", "train_negative", "train_pct_positive",
             "val_rows", "val_groups", "val_positive", "val_negative", "val_pct_positive",
             "both_classes_train", "both_classes_val", "profile_overlap", "result"]
L = [
    "# 03 · Frozen grouped split and cross-validation folds",
    "",
    f"Created (UTC): {created}. Overall status: **{'ALL CHECKS PASSED — split frozen' if all_pass else 'CHECK FAILURE — nothing frozen'}**.",
    "",
    "The split groups rows by `profile_id`, so identical feature profiles never appear on both sides",
    "of any boundary. The audit found no conflicting profiles, so `profile_id` equals `record_id`.",
    "In the deduplicated view every group therefore has exactly one row.",
    "",
    "## Configuration",
    "",
    f"- Test split: `StratifiedGroupKFold(n_splits={TEST_N_SPLITS}, shuffle=True, random_state={TEST_SEED})`.",
    f"  It is run on all 520 rows, with fold {TEST_FOLD} predeclared as the test set.",
    f"- CV: {len(CV_SEEDS)} repeats × `StratifiedGroupKFold(n_splits={CV_N_SPLITS}, shuffle=True)` on the training partition,",
    f"  with `random_state` = {CV_SEEDS}. That gives **{CV_N_SPLITS * len(CV_SEEDS)} folds**.",
    "- Deduplicated view: each row keeps its profile's fold, and only `is_first_copy == 1` rows are used.",
    f"- Input: `cleaned_all_rows.csv`, SHA-256 `{config['input_sha256']}`.",
    f"- Versions: {config['versions']}.",
    "",
    "## Acceptance checks",
    "",
    md_table(pd.DataFrame(checks)),
    "",
    "## Test split counts (permitted split-count report)",
    "",
    md_table(pd.DataFrame(test_rows_report)),
    "",
    "## All 15 CV folds: all-rows view",
    "",
    md_table(fold_df[fold_df["view"] == "all_rows"][show_cols]),
    "",
    "## All 15 CV folds: deduplicated view",
    "",
    md_table(fold_df[fold_df["view"] == "deduplicated"][show_cols]),
    "",
    "## Frozen files",
    "",
]
if all_pass:
    L += [md_table(pd.DataFrame([{"file": k, "sha256": v} for k, v in config["frozen_file_sha256"].items()])),
          "",
          "These files were written once and set read-only. That is an integrity safeguard, not",
          "immutability. Their hashes are re-verified in the Day 1 summary."]
else:
    L += ["_Nothing was frozen. See the failed checks above. The method was not changed._"]
(REPORTS_DIR / "03_split_and_cv.md").write_text("\n".join(L) + "\n")

print(pd.DataFrame(checks).to_string(index=False))
print(pd.DataFrame(test_rows_report).to_string(index=False))
print(fold_df[["repeat", "fold", "view", "train_rows", "train_positive", "train_negative", "val_rows",
               "val_positive", "val_negative", "profile_overlap", "result"]].to_string(index=False))
sys.exit(0 if all_pass else 1)
